@app.post("/api/get-key", status_code=status.HTTP_202_ACCEPTED)
async def register_key_request(payload: KeyRequestPayload):
    """
    Step 1: Called by the script loader when beginning execution.
    Checks license validity, checks dynamic 7-day expiry rules, and registers the pending request.
    """
    file_id = payload.file_id.strip()
    req_id = payload.req_id.strip()

    try:
        file_record = await asyncio.to_thread(get_file, file_id)
    except Exception as e:
        logger.error(f"Database read lookup crash during request validation for file {file_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": "Database lookup execution failed"}
        )

    if not file_record or not file_record.get("decryption_key"):
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"error": "The specified license is invalid, deleted, or does not exist."}
        )

    # 7-day operational check and cleanup logic
    created_at_str = file_record.get("created_at")
    if created_at_str:
        try:
            created_at = datetime.fromisoformat(created_at_str)
            if created_at.tzinfo is None:
                created_at = created_at.replace(tzinfo=IST)
            now = datetime.now(IST)
            age_days = (now - created_at).days
            if age_days >= 7:
                await asyncio.to_thread(delete_file, file_id)  # Autopurges expired files dynamically
                logger.info(f"File ID {file_id} has reached its 7-day operational lifespan and is purged.")
                raise HTTPException(
                    status_code=status.HTTP_403_FORBIDDEN,
                    detail={"error": "License expired. 7-day operational limit reached."}
                )
        except HTTPException:
            raise
        except Exception as date_err:
            logger.error(f"Failed parsing license age indicator for file ID {file_id}: {date_err}")

    owner_id = file_record.get("telegram_id")
    project_name = file_record.get("project_name", "Unnamed Project")

    if not owner_id:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": "Project record is missing key ownership parameters."}
        )

    # Save the authorization request to the database
    now_utc = datetime.now(timezone.utc)
    request_data = {
        "file_id": file_id,
        "owner_id": owner_id,
        "project_name": project_name,
        "status": "pending",
        "created_at": now_utc.isoformat()
    }
    
    try:
        await asyncio.to_thread(fb_set, f"/requests/{req_id}", request_data)
    except Exception as e:
        logger.error(f"Database write execution failed while mapping request {req_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": "Could not register authorization session."}
        )

    # Dispatch interactive button notification to developer asynchronously
    message_id = await send_telegram_authorization_prompt(int(owner_id), req_id, project_name)
    if message_id:
        try:
            await asyncio.to_thread(fb_update, f"/requests/{req_id}", {"message_id": message_id})
        except Exception as update_err:
            logger.warning(f"Failed mapping message callback trace for ID {req_id}: {update_err}")

    return {
        "status": "pending",
        "message": "Authorization request registered. Waiting for owner's response.",
        "req_id": req_id
    }


@app.get("/api/get-key")
async def check_key_status(
    file_id: str = Query(..., min_length=1),
    req_id: str = Query(..., min_length=1)
):
    """
    Step 2: Called continuously by the loader client (polling).
    Returns the key once approved. Enforces strict 30-second server expiration.
    """
    clean_file_id = file_id.strip()
    clean_req_id = req_id.strip()

    try:
        request_record = await asyncio.to_thread(fb_get, f"/requests/{clean_req_id}")
    except Exception as e:
        logger.error(f"Database lookup execution failed while validating request {clean_req_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": "Database lookup failure."}
        )

    if not request_record:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={"error": "Authorization session not found or already terminated."}
        )

    current_status = request_record.get("status", "pending")
    req_created_str = request_record.get("created_at")

    # --- 30-Second Strict Server-Side Expiry Enforcement ---
    if req_created_str and current_status == "pending":
        try:
            req_created_at = datetime.fromisoformat(req_created_str)
            if (datetime.now(timezone.utc) - req_created_at).total_seconds() > 30:
                current_status = "expired"
        except Exception as t_err:
            logger.warning(f"Error parsing timestamp for timeout check: {t_err}")

    if current_status == "pending":
        return JSONResponse(
            status_code=status.HTTP_200_OK,
            content={"status": "pending"}
        )

    elif current_status in ("rejected", "expired"):
        # Instantly purge temporary request parameters
        await asyncio.to_thread(fb_delete, f"/requests/{clean_req_id}")
        return JSONResponse(
            status_code=status.HTTP_200_OK,
            content={"status": "expired" if current_status == "expired" else "rejected"}
        )

    elif current_status == "approved":
        # Pull key directly upon explicit approve actions
        try:
            file_record = await asyncio.to_thread(get_file, clean_file_id)
        except Exception as e:
            logger.error(f"Critical exception while fetching key parameters during approval phase: {e}")
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail={"error": "Internal lookup failure."}
            )

        if not file_record or not file_record.get("decryption_key"):
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail={"error": "Decryption key not found or already deleted."}
            )

        decryption_key = file_record["decryption_key"]

        # Drop temporary requests while preserving the permanent file mapping
        try:
            await asyncio.to_thread(fb_delete, f"/requests/{clean_req_id}")
            logger.info(f"Decryption key verified. Closed request {clean_req_id}, kept file {clean_file_id}.")
        except Exception as cleanup_err:
            logger.warning(f"Failed deleting temporary request node {clean_req_id}: {cleanup_err}")

        return JSONResponse(
            status_code=status.HTTP_200_OK,
            content={
                "status": "approved",
                "key": decryption_key
            }
        )

    else:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": "Invalid request status state detected."}
        )