# --- Custom Exception Handlers ---

@app.exception_handler(HTTPException)
async def custom_http_exception_handler(request: Request, exc: HTTPException):
    """Encapsulates HTTP errors into machine-readable JSON formats."""
    detail = exc.detail
    error_content = detail if isinstance(detail, dict) else {"error": str(detail)}
    
    error_content.update({
        "status": "error",
        "timestamp": datetime.now(timezone.utc).isoformat()
    })
    return JSONResponse(status_code=exc.status_code, content=error_content)


@app.exception_handler(ValidationError)
async def validation_exception_handler(request: Request, exc: ValidationError):
    """Intercepts framework level deserialization or typing failures gracefully."""
    logger.warning(f"Validation failure intercepted on route {request.url.path}: {exc.errors()}")
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content={
            "status": "error",
            "error": "Mismatched or invalid parameters sent in the payload",
            "details": exc.errors(),
            "timestamp": datetime.now(timezone.utc).isoformat()
        }
    )


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    """Global catch-all safety handler to prevent runtime engine leaks."""
    logger.error(f"Fatal unhandled exception on path {request.url.path}: {exc}", exc_info=True)
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content={
            "status": "error",
            "error": "An unexpected system pipeline error occurred.",
            "timestamp": datetime.now(timezone.utc).isoformat()
        }
    )


# --- Internal Transmission Helper (Non-Blocking Async HTTPX) ---

async def send_telegram_authorization_prompt(owner_id: int, req_id: str, project_name: str) -> Optional[int]:
    """Transmits real-time interactive buttons to the user's Telegram interface asynchronously."""
    if not BOT_TOKEN:
        logger.error("BOT_TOKEN environment variable is missing. Cannot dispatch Telegram message.")
        return None

    url = f"https://api.telegram.org/bot{BOT_TOKEN}/sendMessage"
    
    keyboard = {
        "inline_keyboard": [
            [
                {"text": "✅ Approve Access", "callback_data": f"req_accept:{req_id}"},
                {"text": "❌ Reject Request", "callback_data": f"req_reject:{req_id}"}
            ]
        ]
    }
    
    # Safe HTML parse mode
    text = (
        f"🔐 <b>KEY ACCESS REQUEST</b>\n\n"
        f"• <b>Project Name:</b> <code>{project_name}</code>\n"
        f"• <b>Request ID:</b> <code>{req_id}</code>\n\n"
        f"⏳ <i>Note:</i> This request will automatically expire in <b>30 seconds</b> if no action is taken."
    )
    
    payload = {
        "chat_id": owner_id,
        "text": text,
        "parse_mode": "HTML",
        "reply_markup": keyboard
    }
    
    try:
        async with httpx.AsyncClient(timeout=8.0) as client:
            resp = await client.post(url, json=payload)
            if resp.status_code == 200:
                result = resp.json()
                return result.get("result", {}).get("message_id")
            else:
                logger.error(f"Telegram API responded with code {resp.status_code}: {resp.text}")
                return None
    except Exception as e:
        logger.error(f"Network transport failure trying to hit Telegram API: {e}")
        return None


