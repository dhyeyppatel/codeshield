# --- Background Worker: Self-Pinging Uptime Engine ---

async def self_ping_task():
    """
    Background worker that hits the public URL every 8 minutes
    to reset inactivity sleep timer automatically (for container hosts).
    """
    await asyncio.sleep(20)  # Allow initial server startup delay
    
    public_url = (
        os.environ.get("RENDER_EXTERNAL_URL") or 
        os.environ.get("APP_URL") or 
        os.environ.get("SELF_PING_URL")
    )

    if not public_url:
        logger.warning(
            "⚠️ Self-ping worker skipped: No 'RENDER_EXTERNAL_URL' or 'APP_URL' found."
        )
        return

    logger.info(f"🔄 Self-ping background worker initialized for: {public_url}")
    
    async with httpx.AsyncClient(timeout=30.0) as client:
        while True:
            try:
                await asyncio.sleep(480)  # Ping every 8 minutes (480 seconds)
                resp = await client.get(public_url)
                logger.info(f"⚡ Self-ping heartbeat successful! HTTP Status: {resp.status_code}")
            except asyncio.CancelledError:
                logger.info("Self-ping worker task cancelled.")
                break
            except Exception as e:
                logger.error(f"❌ Self-ping heartbeat error: {e}")


# --- Lifespan Manager ---

@asynccontextmanager
async def lifespan(app: FastAPI):
    global _firebase_ready
    logger.info("Initializing Licensing Engine...")
    try:
        # Offload synchronous Firebase init to threadpool
        await asyncio.to_thread(init_firebase)
        _firebase_ready = True
        logger.info("Database instance handshaked successfully.")
    except Exception as e:
        logger.error(f"Database initialization step failed on startup: {e}", exc_info=True)

    # Start the Self-Ping Engine (if URL is set)
    ping_task = asyncio.create_task(self_ping_task())

    yield

    # Cleanup background worker on server shutdown
    ping_task.cancel()
    try:
        await ping_task
    except asyncio.CancelledError:
        pass
    logger.info("Shutting down Licensing Engine...")


